#!/usr/bin/env bash
# qscratch.sh - run "make qemu-check" on a scratch copy of the project in
# which missing kernels are replaced by stubs.
#
# The real qemu-check needs every kernel (table.c references all ids).  While
# kernels are still being written, this copies include/, src/kernels/ and
# tools/ into a scratch directory, keeps every real kernel file, fills the
# missing ids with tools/qemu/stubs/<cat>_<id>.c (AltiVec intrinsics, BLIB,
# sqrt, libgcc-helper and byte-order stubs) or a generic EXACT stub, and runs
# the check there.  Nothing in the project tree is modified.
#
#   tools/qemu/qscratch.sh [-k] [-S] [-o dir] [make arguments...]
#     -k      also run tools/kcheck.sh on each real kernel (in the copy) and
#             stub the ones that fail it
#     -S      stubs only: ignore the real kernels (tests the runner itself)
#     -o dir  scratch directory (default: $TMPDIR/qscratch)
set -u
root=$(cd "$(dirname "$0")/../.." && pwd)
scratch=${TMPDIR:-/tmp}/qscratch
kcheck=0
stubs_only=0
while [ $# -gt 0 ]; do
	case $1 in
	-k) kcheck=1; shift ;;
	-S) stubs_only=1; shift ;;
	-o) scratch=$2; shift 2 ;;
	*) break ;;
	esac
done

# copy a file only if its content changed (keeps make's timestamps useful)
sync_file() {
	mkdir -p "$(dirname "$2")"
	cmp -s "$1" "$2" 2>/dev/null || cp "$1" "$2"
}

mkdir -p "$scratch/src/kernels" "$scratch/include" "$scratch/tools/qemu/stubs"
for f in "$root"/include/*.h; do sync_file "$f" "$scratch/include/${f##*/}"; done
for f in "$root"/src/kernels/*.h "$root"/src/kernels/table.c; do sync_file "$f" "$scratch/src/kernels/${f##*/}"; done
for f in "$root"/tools/kcheck.sh "$root"/tools/ktest.c; do sync_file "$f" "$scratch/tools/${f##*/}"; done
for f in "$root"/tools/qemu/*.* "$root"/tools/qemu/stubs/*.c; do
	sync_file "$f" "$scratch/tools/qemu/${f#"$root"/tools/qemu/}"
done
chmod +x "$scratch/tools/kcheck.sh"

real=() stubbed=() failed=()
wanted=()
for list in "$root"/src/kernels/list_*.h; do
	cat=${list##*/list_}
	cat=${cat%.h}
	for id in $(sed -n 's/^BENCH_LIST(\([a-z0-9]*\)).*/\1/p' "$list"); do
		f=${cat}_$id.c
		wanted+=("$f")
		use_real=0
		if [ -f "$root/src/kernels/$f" ] && [ $stubs_only -eq 0 ]; then
			use_real=1
			if [ $kcheck -eq 1 ]; then
				sync_file "$root/src/kernels/$f" "$scratch/src/kernels/$f"
				if ! (cd "$scratch" && ./tools/kcheck.sh "src/kernels/$f" "$id" >"$scratch/kcheck_$id.log" 2>&1); then
					use_real=0
					failed+=("$id")
				fi
			fi
		fi
		if [ $use_real -eq 1 ]; then
			sync_file "$root/src/kernels/$f" "$scratch/src/kernels/$f"
			real+=("$id")
		elif [ -f "$root/tools/qemu/stubs/$f" ]; then
			sync_file "$root/tools/qemu/stubs/$f" "$scratch/src/kernels/$f"
			stubbed+=("$id")
		else
			CAT=$(echo "$cat" | tr a-z A-Z)
			cat >"$scratch/stub.tmp" <<STUB
/* qemu scratch stub for $id (generated by tools/qemu/qscratch.sh). */
#include "bench_kernel.h"

#define N 8192u

static void ${id}_init(void *arena)
{
	uint32_t *a = (uint32_t *)arena;
	bench_rng r;
	uint32_t i;

	bench_rng_seed(&r, 0x51ab0000u + ${#id}u);
	for (i = 0; i < N; i++)
		a[i] = bench_rng_next(&r);
}

static double ${id}_run(void *arena)
{
	const uint32_t *a = (const uint32_t *)arena;
	uint32_t i, h = 0;

	for (i = 0; i < N; i++)
		h = bench_mix(h, a[i] ^ (a[i] >> (a[i] & 15u)) ^ (a[i] % 1000u));
	return bench_result_u32(h);
}

BENCH_KDEF($id) = {
	.name = "$id", .desc = "qemu generic stub", .unit = "w",
	.category = BENCH_CAT_$CAT, .flags = BENCH_F_EXACT, .tolerance = 0.0,
	.units = N, .arena_bytes = N * 4u,
	.init = ${id}_init, .run = ${id}_run,
};
STUB
			sync_file "$scratch/stub.tmp" "$scratch/src/kernels/$f"
			stubbed+=("$id")
		fi
	done
done
rm -f "$scratch/stub.tmp"
# drop kernel files that no list names any more
for f in "$scratch"/src/kernels/*_*.c; do
	case " ${wanted[*]} " in *" ${f##*/} "*) ;; *) rm -f "$f" ;; esac
done

echo "qscratch: $scratch"
echo "  real kernels (${#real[@]}): ${real[*]:-}"
echo "  stubbed      (${#stubbed[@]}): ${stubbed[*]:-}"
[ ${#failed[@]} -eq 0 ] || echo "  stubbed because tools/kcheck.sh failed: ${failed[*]} (logs: $scratch/kcheck_<id>.log)"
exec make --no-print-directory -C "$scratch" -f tools/qemu/qemu.mk qemu-check "$@"
