#!/usr/bin/env python3
"""gen_quarantine.py - quarantine.txt -> C header (compiled into the run driver, src/core/main.c).

  python3 tools/gen_quarantine.py quarantine.txt > build/gen/quarantine.h

Lines: "<family> <case_id>" (case_id "*" = the whole family); '#' starts a comment; blank lines are ignored.
Exit 1 on a malformed line (more or fewer than two fields, or characters a C string cannot hold plainly).
"""
import re
import sys


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: gen_quarantine.py quarantine.txt")
    entries, bad = [], []
    try:
        lines = open(sys.argv[1], encoding="utf-8").read().splitlines()
    except FileNotFoundError:
        lines = []
    for n, line in enumerate(lines, 1):
        text = line.split("#", 1)[0].strip()
        if not text:
            continue
        f = text.split()
        if len(f) != 2 or not all(re.fullmatch(r"[\x21-\x7e]+", x) and '"' not in x and "\\" not in x for x in f):
            bad.append("%s:%d: %r" % (sys.argv[1], n, line))
            continue
        if tuple(f) not in entries:
            entries.append(tuple(f))
    if bad:
        sys.stderr.write("gen_quarantine: malformed line(s):\n  " + "\n  ".join(bad) + "\n")
        return 1
    out = ["/* generated by tools/gen_quarantine.py from quarantine.txt - do not edit */",
           "#define XTS_QUARANTINE_N %d" % len(entries),
           "static const xts_quar_t xts_quarantine_builtin[%d] = {" % max(1, len(entries))]
    out += ['  { "%s", "%s" },' % e for e in entries] or ["  { 0, 0 },"]
    out.append("};")
    sys.stdout.write("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
