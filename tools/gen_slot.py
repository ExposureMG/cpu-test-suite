#!/usr/bin/env python3
"""Generate slot.S: load a full machine-state image, execute ONE patched word (or branch into a kernel), store the full
state back, restore the C runtime. Port of OpenXenos isa/hwtest/runner/gen_slot.py, now with real mnemonics for the
VMX128 registers (lvx128/stvx128 need `-Wa,-mvmx128`).

    gen_slot.py > $(BUILD)/gen/slot.S

int xts_slot_run(const xts_state_t *in, xts_state_t *out)   (r3 = IN image, r4 = OUT image; both 32-bit addresses)

Changes from the OpenXenos runner:
  * the C runtime's FPSCR, VSCR and VRSAVE are saved on entry and restored on exit (the old runner leaked the case's
    FPSCR/VSCR into the C code that ran next);
  * symbols are xts_slot_run / xts_slot_insn / xts_slot_post.
Layout constants come from include/xts/state.h (XTS_ST_*).
"""
import sys

OUT = []
w = OUT.append

ST_VR = 0x250
SAVE = dict(gpr=0, fpr=144, cr=288, lr=296, vr=304, fpscr=496, vscr=512, vrsave=528, size=576)

w('/* GENERATED by tools/gen_slot.py - do not edit. */')
w('#include <xts/state.h>')
w('\t.section .text')
w('\t.globl xts_slot_run')
w('\t.globl xts_slot_insn')
w('\t.globl xts_slot_post')
w('\t.globl xts_slot_end')
w('')
w('\t.align 7')
w('xts_slot_run:')
w('\tclrldi 3, 3, 32')
w('\tclrldi 4, 4, 32')
w('\t/* the C caller\'s non-volatile state goes to xts_slot_save (NOT the stack: the case owns every GPR but r1 r2 r13) */')
w('\tlis 5, xts_slot_save@ha')
w('\taddi 5, 5, xts_slot_save@l')
for i, r in enumerate(range(14, 32)):
  w('\tstd %d, %d(5)' % (r, SAVE['gpr'] + i * 8))
for i, r in enumerate(range(14, 32)):
  w('\tstfd %d, %d(5)' % (r, SAVE['fpr'] + i * 8))
w('\tmfcr 0')
w('\tstd 0, %d(5)' % SAVE['cr'])
w('\tmflr 0')
w('\tstd 0, %d(5)' % SAVE['lr'])
for i, v in enumerate(range(20, 32)):
  w('\tli 0, %d' % (SAVE['vr'] + i * 16))
  w('\tstvx %d, 5, 0' % v)
w('\t/* C runtime FPSCR, VSCR, VRSAVE */')
w('\tmffs 0')
w('\tstfd 0, %d(5)' % SAVE['fpscr'])
w('\tmfvscr 0')
w('\tli 0, %d' % SAVE['vscr'])
w('\tstvx 0, 5, 0')
w('\tmfspr 6, 256')
w('\tstw 6, %d(5)' % SAVE['vrsave'])
w('\tmfmsr 6')
w('\tstd 6, XTS_ST_SAVEDMSR(4)')
w('\tmr 30, 3')
w('\t/* optional 64-bit mode (games run with MSR[SF]=1; libxenon runs with it clear) */')
w('\tld 7, XTS_ST_MODE(30)')
w('\tandi. 7, 7, XTS_MODE_SF')
w('\tbeq 1f')
w('\tli 7, 1')
w('\tsldi 7, 7, 63')
w('\tor 6, 6, 7')
w('\tmtmsrd 6')
w('\tisync')
w('1:')
w('\t/* FPSCR first (an FPR load sequence must not be disturbed by it), then FPRs */')
w('\tlfd 0, XTS_ST_FPSCR(30)')
w('\tmtfsf 255, 0')
for r in range(32):
  w('\tlfd %d, %d(30)' % (r, 0x100 + r * 8))
w('\tli 0, XTS_ST_VSCR')
w('\tlvx 0, 30, 0')
w('\tmtvscr 0')
for n in range(128):
  w('\tli 0, %d' % (ST_VR + 16 * n))
  w('\t%s %d, 30, 0' % ('lvx' if n < 32 else 'lvx128', n))
w('\tld 0, XTS_ST_CR(30)')
w('\tmtcrf 255, 0')
w('\tld 0, XTS_ST_XER(30)')
w('\tmtxer 0')
w('\tld 0, XTS_ST_LR(30)')
w('\tmtlr 0')
w('\tld 0, XTS_ST_CTR(30)')
w('\tmtctr 0')
for r in list(range(1, 30)) + [31]:
  if r in (1, 2, 13):
    continue
  w('\tld %d, %d(30)' % (r, r * 8))
w('\tld 0, 0(30)')
w('\tld 30, XTS_ST_OUTPTR(30)')
w('')
w('/* ---- the patched instruction (or a branch into the kernel buffer) ---- */')
w('\t.align 7')
w('xts_slot_insn:')
w('\tnop')
w('\tb xts_slot_post\t\t/* fall-through */')
w('\tb xts_slot_post\t\t/* a taken +8 branch lands here */')
w('\tb xts_slot_post')
w('/* landing pads (XTS_SLOT_PAD1/PAD2): a branch test aims here, so "taken" leaves a mark in the OUT image.')
w('   r30 is the OUT image pointer, never zero. */')
w('\tstw 30, XTS_ST_MARK(30)\t\t/* +16: pad 1 */')
w('\tb xts_slot_post')
w('\tstw 30, XTS_ST_MARK+4(30)\t\t/* +24: pad 2 */')
w('\tb xts_slot_post')
w('xts_slot_end:')
w('')
w('xts_slot_post:')
for r in list(range(0, 30)) + [31]:
  if r in (1, 2, 13):
    continue
  w('\tstd %d, %d(30)' % (r, r * 8))
w('\tmfcr 0')
w('\tstd 0, XTS_ST_CR(30)')
w('\tmfxer 0')
w('\tstd 0, XTS_ST_XER(30)')
w('\tmflr 0')
w('\tstd 0, XTS_ST_LR(30)')
w('\tmfctr 0')
w('\tstd 0, XTS_ST_CTR(30)')
for r in range(32):
  w('\tstfd %d, %d(30)' % (r, 0x100 + r * 8))
w('\tmffs 0')
w('\tstfd 0, XTS_ST_FPSCR(30)')
for n in range(128):
  w('\tli 0, %d' % (ST_VR + 16 * n))
  w('\t%s %d, 30, 0' % ('stvx' if n < 32 else 'stvx128', n))
w('\tmfvscr 0')
w('\tli 0, XTS_ST_VSCR')
w('\tstvx 0, 30, 0')
w('\tld 0, XTS_ST_SAVEDMSR(30)')
w('\tmtmsrd 0')
w('\tisync')
w('\tlis 5, xts_slot_save@ha')
w('\taddi 5, 5, xts_slot_save@l')
for i, r in enumerate(range(14, 32)):
  w('\tld %d, %d(5)' % (r, SAVE['gpr'] + i * 8))
for i, r in enumerate(range(14, 32)):
  w('\tlfd %d, %d(5)' % (r, SAVE['fpr'] + i * 8))
for i, v in enumerate(range(20, 32)):
  w('\tli 0, %d' % (SAVE['vr'] + i * 16))
  w('\tlvx %d, 5, 0' % v)
w('\t/* C runtime FPSCR, VSCR, VRSAVE back */')
w('\tlfd 0, %d(5)' % SAVE['fpscr'])
w('\tmtfsf 255, 0')
w('\tli 0, %d' % SAVE['vscr'])
w('\tlvx 0, 5, 0')
w('\tmtvscr 0')
w('\tlwz 6, %d(5)' % SAVE['vrsave'])
w('\tmtspr 256, 6')
w('\tld 0, %d(5)' % SAVE['cr'])
w('\tmtcrf 255, 0')
w('\tld 0, %d(5)' % SAVE['lr'])
w('\tmtlr 0')
w('\tli 3, 0')
w('\tblr')
w('')
w('\t.section .bss')
w('\t.align 7')
w('\t.globl xts_slot_save')
w('xts_slot_save:')
w('\t.space %d' % SAVE['size'])

sys.stdout.write('\n'.join(OUT) + '\n')
