HTEST(hw_sem_fp_single)
{
  int bad = 0;
  for (size_t i = 0; i < sizeof hw_fp / sizeof hw_fp[0]; i++) {
    const hw_fp_t *c = &hw_fp[i];
    xts_state_t S, O;
    xts_mem_t m;
    xts_state_baseline(&S);
    for (int k = 0; k < c->nr; k++) S.fpr[c->r[k]] = c->v[k];
    S.cr = c->cr;
    S.fpscr = c->fpscr;
    S.xer = c->xer;
    xts_mem_init(&m);
    O = S;
    HT_EQ_U64(xts_model_exec(NULL, c->w, &S, &m, &O), XTS_M_OK);
    int ok = (!(c->known & 1) || O.fpr[c->t] == c->efpr) && (!(c->known & 2) || (uint32_t)O.fpscr == c->efpscr) &&
             (!(c->known & 4) || (uint32_t)O.cr == c->ecr);
    if (!ok) {
      bad++;
      printf("    %s %08X: fpr %016llX/%016llX fpscr %08X/%08X cr %08X/%08X (model/cpu)\n", c->id, (unsigned)c->w,
             (unsigned long long)O.fpr[c->t], (unsigned long long)c->efpr, (unsigned)O.fpscr, (unsigned)c->efpscr,
             (unsigned)O.cr, (unsigned)c->ecr);
    }
  }
  HT_EQ_U64(bad, 0);
}
